//------------------------------------------------------------------------------
// soc_top.v — SoC Top Level (SoC 顶层集成)
//------------------------------------------------------------------------------
// 功能：
//   集成处理器核心和存储器，构成完整的最小系统
//
// 结构：
//   soc_top
//   ├── core (处理器核心)
//   │   ├── pc
//   │   ├── regfile
//   │   ├── alu
//   │   ├── imm_gen
//   │   └── control_unit
//   └── memory (统一指令/数据存储器)
//
// 在单周期冯·诺依曼架构中，指令和数据共享一个 memory 实例。
// core 的指令取指和数据访存都会访问 memory，但单周期设计保证不会冲突。
//
// 接口：
//   clk, rst_n — 时钟与复位
//   (内部无额外IO—这是一个完全封闭的SoC)
//
// 设计要点：
//   - 这是仿真顶层的实例化模板
//   - 所有模块在此互联
//   - 调试信号可在此引出
//------------------------------------------------------------------------------

module soc_top (
    input  wire clk,
    input  wire rst_n
);

    //--------------------------------------------------------------------------
    // 内部互联信号
    //--------------------------------------------------------------------------

    // 指令存储器接口
    wire [31:0] instr;
    wire [31:0] pc;

    // 数据存储器接口
    wire [31:0] dmem_addr;
    wire [31:0] dmem_wdata;
    wire [31:0] dmem_rdata;
    wire        dmem_we;
    wire        dmem_re;

    //--------------------------------------------------------------------------
    // 子模块实例化
    //--------------------------------------------------------------------------

    // 处理器核心
    core u_core (
        .clk          (clk),
        .rst_n        (rst_n),
        .instr_i      (instr),
        .pc_o         (pc),
        .mem_addr_o   (dmem_addr),
        .mem_wdata_o  (dmem_wdata),
        .mem_rdata_i  (dmem_rdata),
        .mem_write_o  (dmem_we),
        .mem_read_o   (dmem_re)
    );

    // 统一存储器
    // TODO: memory 目前使用统一的 I/D 端口连接
    // 实际连接方式取决于 memory.v 的接口设计
    // 注意单周期设计中指令和数据访问不会冲突
    memory u_memory (
        .clk     (clk),
        .i_addr  (pc),
        .i_rdata (instr),
        .d_addr  (dmem_addr),
        .d_wdata (dmem_wdata),
        .d_rdata (dmem_rdata),
        .d_we    (dmem_we),
        .d_re    (dmem_re)
    );

endmodule
