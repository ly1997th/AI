//==============================================================================
// regfile.v — 寄存器文件 (Register File)
//==============================================================================
//
// 【电路架构】
// ┌──────────────────────────────────────────────────────────────┐
// │  功能：32×32-bit 通用寄存器阵列，2读1写三端口结构。              │
// │                                                              │
// │  数据通路（32-bit）：                                          │
// │                                                              │
// │    写侧：                                                     │
// │      wd3[31:0] ──→ [wr_data MUX per bit] ──→ rf[a3][31:0]   │
// │                          ↑                                   │
// │                     we3 & (a3 != 0)                           │
// │                                                              │
// │    读侧（组合逻辑，零延迟）：                                   │
// │      rf[a1] ──→ [x0 bypass] ──→ rd1[31:0]                    │
// │      rf[a2] ──→ [x0 bypass] ──→ rd2[31:0]                    │
// │                                                              │
// │  地址通路（5-bit）：                                           │
// │    a1[4:0] ──→ [5:32 Decoder] ──→ 32路读字线（读端口1）       │
// │    a2[4:0] ──→ [5:32 Decoder] ──→ 32路读字线（读端口2）       │
// │    a3[4:0] ──→ [5:32 Decoder] ──→ 32路写字线                 │
// │                                                              │
// │  控制通路：                                                    │
// │    we3 ──→ 写使能门控（与 a3!=0 条件 AND）                    │
// │            扇出=32（驱动所有32个寄存器的WE端）                  │
// │                                                              │
// │  路径分离分析：                                                │
// │    - 数据通路：32-bit 宽，经 MUX 网络至输出（读路径关键延时）     │
// │    - 地址通路：5-bit 译码器输出为 32-bit one-hot 字线，         │
// │               扇出极大（每根字线驱动32个bit-cell），             │
// │               需要缓冲树（BUFF insertion）                     │
// │    - 控制通路：we3 扇出=32，需关注写使能 buffer                 │
// │    - 重汇聚：a1/a2 经译码器后驱动 MUX 网络，                    │
// │              MUX 级联深度 = ceil(log2(32)) = 5 级             │
// │    - 关键路径：地址译码 → 字线驱动 → bit-cell读出 → MUX级联      │
// │               ≈ 1(decoder)+1(wl)+5(mux) ≈ 7 级逻辑深度        │
// └──────────────────────────────────────────────────────────────┘
//
// 【宏单元映射与PPA评估】
// ┌──────────────────────────────────────────────────────────────┐
// │  宏单元清单：                                                  │
// │    · 32×32 DFF 阵列（1024 DFF，构成 rf[31:0]）                │
// │    · 2× 5:32 Decoder（读地址译码，one-hot 输出）               │
// │    · 1× 5:32 Decoder（写地址译码）                             │
// │    · 2× 32-to-1 32-bit MUX（读端口1/2，面积主要贡献者）         │
// │    · 1× 5-bit Comparator（a3 == 0 检测，x0 写保护）            │
// │    · 2× 32-bit 2-to-1 MUX（x0 读旁路）                        │
// │                                                              │
// │  互联关系（高扇出关注点）：                                     │
// │    · 译码器 → 字线（扇出=32/每根，需缓冲树）                    │
// │    · 字线 → bit-cell 选择端（扇出=32 DFF/每根）                │
// │    · 读 MUX 级联：32→16→8→4→2→1（5级MUX树）                    │
// │    · we3 AND (a3!=0) → 32个寄存器的写使能（扇出=32）            │
// │                                                              │
// │  PPA评估（精度分级：低敏感度—基于逻辑分析）：                     │
// │    · 面积：~1024 DFF + 3 译码器 + 2 大MUX树 ≈ 3000-5000门当量   │
// │            寄存器文件是核心数据通路中面积最大的模块之一           │
// │    · 时序：关键路径 = 地址译码(1级) + 字线(1级)                 │
// │           + MUX级联(5级) ≈ 7级逻辑深度                         │
// │            实际延时受工艺库和 bit-cell 驱动强度影响显著          │
// │    · 功耗：时钟翻转为主（1024 DFF 的 CK 端），                   │
// │            读端口纯组合无时钟，写端口仅 we3=1 时有活动            │
// │    · 工艺依赖性：RF2P（2读端口）vs RF1P（1读端口）的面积增量为    │
// │                  额外的1套译码器 + 1套MUX网络，                 │
// │                  不同工艺下增量比例差异大（10%-100%不等）         │
// │    · 优化方向：可用 SRAM 替代 DFF 阵列（面积更优但时序更差），    │
// │              或引入 ICG 降低未使用寄存器的时钟功耗               │
// └──────────────────────────────────────────────────────────────┘
//
// 【RTL代码】
//==============================================================================

module regfile (
    input  wire        clk,
    input  wire        rst_n,
    // 读端口 1
    input  wire [4:0]  a1,      // rs1 地址
    output wire [31:0] rd1,     // rs1 数据
    // 读端口 2
    input  wire [4:0]  a2,      // rs2 地址
    output wire [31:0] rd2,     // rs2 数据
    // 写端口
    input  wire [4:0]  a3,      // rd 地址
    input  wire        we3,     // RegWrite
    input  wire [31:0] wd3      // 写数据
);

    // 32×32 DFF 阵列（综合工具映射为 DFF 或 SRAM）
    reg [31:0] rf [31:0];

    //----------------------------------------------------------------------
    // 读通路：2× 32-to-1 32-bit MUX + x0 旁路
    // 纯组合逻辑，零时钟延迟
    //----------------------------------------------------------------------
    // x0 硬件实现：a==0 时强行为 0，否则读取 rf[a]（MUX选择）
    assign rd1 = (a1 == 5'b0) ? 32'b0 : rf[a1];
    assign rd2 = (a2 == 5'b0) ? 32'b0 : rf[a2];

    //----------------------------------------------------------------------
    // 写通路：1× 5:32 Decoder + 32× DFF（带写使能）
    // 时序逻辑：posedge clk 写入
    //----------------------------------------------------------------------
    // 地址译码：a3 经过 5:32 Decoder → 选中 1 个寄存器
    // 写保护：x0（a3=0）的写使能被硬件屏蔽
    integer i;
    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            // 异步复位：所有寄存器清零
            for (i = 0; i < 32; i = i + 1)
                rf[i] <= 32'b0;
        end else if (we3 && (a3 != 5'b0)) begin
            // 写使能 AND x0 保护 → 驱动选中 DFF 的 D 端
            rf[a3] <= wd3;
        end
    end

endmodule
