// ============================================================================
// valid_ready_regslice.v  —  Valid/Ready 协议流水线寄存器级
// ============================================================================
// 功能：在 valid/ready 握手链中插入一级寄存器，将 upstream 和 downstream
//       隔离开。所有输出均为寄存器输出（包括 i_ready），有利于时序收敛。
//
// 架构：单级缓冲（buf_full 状态机）
//   EMPTY (buf_full=0): i_ready=1, o_valid=0  — 等待上游数据
//   FULL  (buf_full=1): i_ready=0, o_valid=1  — 向下游展示数据
//
// 传输条件（两边沿时钟）：
//   上游 → 本模块：i_valid && i_ready
//   本模块 → 下游：o_valid && o_ready
// ============================================================================

module valid_ready_regslice #(
    parameter DATA_WIDTH = 32          // 数据位宽，可按需修改
) (
    input  wire                     clk,
    input  wire                     rst_n,      // 异步复位，低有效

    // ===================== 上游接口（输入侧） =====================
    input  wire                     i_valid,    // 上游数据有效
    output reg                      i_ready,    // 本模块可接收（寄存器输出）
    input  wire [DATA_WIDTH-1:0]    i_dat,      // 上游数据

    // ===================== 下游接口（输出侧） =====================
    output reg                      o_valid,    // 本模块数据有效
    input  wire                     o_ready,    // 下游可接收
    output reg  [DATA_WIDTH-1:0]    o_dat       // 输出数据
);

    // ----------------------------------------------------------------------
    // 内部状态寄存器
    // ----------------------------------------------------------------------
    // buf_full == 1'b0 : 缓冲器为空，等待上游提供数据
    // buf_full == 1'b1 : 缓冲器持有一笔有效数据，正在向下游展示
    // ----------------------------------------------------------------------
    reg buf_full;

    // ======================================================================
    // 主状态机 — 单 always 块，所有分支完整
    // ======================================================================
    always @(posedge clk or negedge rst_n)
    begin
        if (!rst_n)
        begin
            // 复位：清空缓冲，向上游表示就绪
            buf_full <= 1'b0;
            o_valid  <= 1'b0;
            o_dat    <= {DATA_WIDTH{1'b0}};
            i_ready  <= 1'b1;
        end
        else
        begin

            if (buf_full)
            begin
                // ==========================================================
                // 状态：FULL — 缓冲器中有一笔待消费的数据
                // ==========================================================
                if (o_ready)
                begin
                    // 下游握手成功 → 数据被取走 → 回到 EMPTY
                    buf_full <= 1'b0;
                    o_valid  <= 1'b0;
                    i_ready <= 1'b1;        // 可以接收新数据
                end
                else
                begin
                    // 下游未就绪 → 保持 FULL，数据继续有效
                    buf_full <= 1'b1;
                    o_valid  <= 1'b1;
                    i_ready <= 1'b0;        // 满了，不能再收
                end
            end
            else
            begin
                // ==========================================================
                // 状态：EMPTY — 缓冲器空闲，等待上游数据
                // ==========================================================
                if (i_valid)
                begin
                    // 上游握手成功 → 锁存数据 → 进入 FULL
                    o_dat    <= i_dat;       // 锁存上游数据
                    buf_full <= 1'b1;
                    o_valid  <= 1'b1;
                    i_ready <= 1'b0;        // 已满，停止接收
                end
                else
                begin
                    // 上游无数据 → 保持 EMPTY
                    buf_full <= 1'b0;
                    o_valid  <= 1'b0;
                    i_ready <= 1'b1;        // 持续就绪
                end
            end
        end
    end

endmodule
